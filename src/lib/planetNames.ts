import type { Planet, PlanetType } from "../types/campaign";

/** First world is "Prime"; further worlds use Roman numerals. */
const WORLD_SUFFIXES = [
  "Prime",
  "II",
  "III",
  "IV",
  "V",
  "VI",
  "VII",
  "VIII",
  "IX",
  "X",
  "XI",
  "XII",
  "XIII",
  "XIV",
  "XV",
  "XVI",
  "XVII",
  "XVIII",
  "XIX",
  "XX",
] as const;

function systemLabel(systemName: string): string {
  const trimmed = systemName.trim();
  return trimmed || "System";
}

function worldSuffix(zeroBasedIndex: number): string {
  return WORLD_SUFFIXES[zeroBasedIndex] ?? String(zeroBasedIndex + 1);
}

function isWorldBody(type: PlanetType): boolean {
  return type !== "asteroid_belt" && type !== "warp_gate";
}

/**
 * Default name for a newly added body in a system.
 * Worlds: "{System} Prime", "{System} II", …
 * Asteroid belts: "{System} debris field"
 * Warp gates: "{System} warp gate"
 */
export function defaultPlanetName(
  systemName: string,
  type: PlanetType,
  siblingsInSystem: Planet[],
): string {
  const base = systemLabel(systemName);
  if (type === "asteroid_belt") return `${base} debris field`;
  if (type === "warp_gate") return `${base} warp gate`;
  const worldCount = siblingsInSystem.filter((p) => isWorldBody(p.type)).length;
  return `${base} ${worldSuffix(worldCount)}`;
}

/** True when the name still matches an auto-assigned default for this system. */
export function isAutoGeneratedPlanetName(
  name: string,
  systemName: string,
): boolean {
  const base = systemLabel(systemName);
  const n = name.trim();
  if (!n) return true;
  if (/^Planet \d+$/i.test(n)) return true;
  if (n.toLowerCase() === `${base} debris field`.toLowerCase()) return true;
  if (n.toLowerCase() === `${base} warp gate`.toLowerCase()) return true;
  const prefix = `${base} `;
  if (!n.startsWith(prefix)) return false;
  const suffix = n.slice(prefix.length);
  if ((WORLD_SUFFIXES as readonly string[]).includes(suffix)) return true;
  return /^\d+$/.test(suffix) && Number(suffix) > WORLD_SUFFIXES.length;
}
